import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,...(process.env.CHROME_EXECUTABLE?{executablePath:process.env.CHROME_EXECUTABLE}:{})});
const errors=[];
try{
 const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'no-preference'});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle',timeout:45000});
 const layers=page.locator('.food-layer');
 assert.equal(await layers.count(),6);
 assert(await layers.evaluateAll(nodes=>nodes.every(x=>x.complete&&x.naturalWidth>0)),'all 6 real-photo ingredient layers must load');
 await page.waitForFunction(()=>document.querySelector('#heroPhoto')?.dataset.state==='complete',undefined,{timeout:13000});
 await page.waitForFunction(()=>Number(getComputedStyle(document.querySelector('#heroPhotoFull')).opacity)>.98,undefined,{timeout:4500});
 console.log('PASS: six real cutout food layers load and assemble into photo');
 await page.locator('#replay').click();
 await page.waitForFunction(()=>document.querySelector('#heroPhoto')?.dataset.state==='playing',undefined,{timeout:4000});
 await page.waitForTimeout(250);
 const a=await page.locator('#heroPhoto').screenshot({animations:'allow'});
 const t1=await layers.nth(5).evaluate(el=>getComputedStyle(el).transform);
 await page.waitForTimeout(600);
 const b=await page.locator('#heroPhoto').screenshot({animations:'allow'});
 const t2=await layers.nth(5).evaluate(el=>getComputedStyle(el).transform);
 assert(!a.equals(b),'rendered burger photograph must visibly change between frames');
 assert.notEqual(t1,t2,'food layers must measurably move');
 await page.waitForFunction(()=>document.querySelector('#heroPhoto')?.dataset.state==='complete',undefined,{timeout:10000});
 console.log('PASS: real visible image motion, not just animation class / replay button');
 await page.locator('#builder').scrollIntoViewIfNeeded();
 await page.waitForTimeout(350);
 const before=await page.locator('.builder-photo-box').evaluate(el=>getComputedStyle(el).transform);
 await page.locator('#lastCall').scrollIntoViewIfNeeded();
 await page.waitForTimeout(350);
 const after=await page.locator('.builder-photo-box').evaluate(el=>getComputedStyle(el).transform);
 assert.notEqual(before,after,'scroll must transform builder photo');
 console.log('PASS: scroll visibly moves the photographic burger');
 for(const [c,n] of [['burgers',4],['sides',4],['drinks',4],['desserts',3],['combos',2]]){
  await page.locator('[data-cat="'+c+'"]').click();
  assert.equal(await page.locator('.product-card').count(),n);
 }
 await page.locator('[data-cat="burgers"]').click();
 await page.locator('#menuPanel [data-add="district"]').click();
 assert.equal(await page.locator('#bagCount').textContent(),'1');
 console.log('PASS: categorized menu and demo cart remain functional');
 await page.screenshot({path:'motion-desktop.png',fullPage:true,timeout:30000});
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'no-preference'});
 mobile.on('pageerror',e=>errors.push('mobile: '+e.message));
 await mobile.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle',timeout:45000});
 await mobile.waitForFunction(()=>document.querySelector('#heroPhoto')?.dataset.state==='complete',undefined,{timeout:14000});
 await mobile.locator('#replay').click();
 await mobile.waitForTimeout(250);
 const m1=await mobile.locator('#heroPhoto').screenshot({animations:'allow'});
 await mobile.waitForTimeout(670);
 const m2=await mobile.locator('#heroPhoto').screenshot({animations:'allow'});
 assert(!m1.equals(m2),'burger must visibly animate on mobile');
 await mobile.screenshot({path:'motion-mobile.png',timeout:25000});
 console.log('PASS: real moving photo visible on mobile');
 assert.equal(errors.length,0,'uncaught browser errors: '+errors.join('; '));
 console.log('PASS: zero runtime errors desktop and mobile');
 await mobile.close();await page.close();
 const accessible=await browser.newPage({reducedMotion:'reduce'});
 await accessible.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
 await accessible.waitForFunction(()=>document.querySelector('#heroPhoto')?.dataset.state==='complete',undefined,{timeout:6500});
 assert(await accessible.locator('#heroPhotoFull').evaluate(el=>Number(getComputedStyle(el).opacity)>.98));
 console.log('PASS: reduced-motion fallback displays static burger');
 await accessible.close();
}finally{await browser.close();}
