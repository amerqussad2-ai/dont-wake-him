import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true});
const errors=[];
try{
 const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle',timeout:35000});
 await page.waitForFunction(()=>document.querySelector('#loading')?.classList.contains('done'),undefined,{timeout:7000});
 assert.match(await page.title(),/SMASH DISTRICT/);
 assert.equal(await page.locator('.feature-card').count(),3);
 assert.equal(await page.locator('.menu-item').count(),26);
 assert.equal(await page.locator('#heroBurger').evaluate(img=>img.complete&&img.naturalWidth>0),true,'hero image must be first-party and loaded');
 console.log('PASS hero image, three featured products and 26-item menu');
 await page.locator('button[data-filter="sides"]').click();
 assert.equal(await page.locator('.menu-item').count(),5,'filter should show five sides');
 await page.locator('button[data-filter="burgers"]').click();
 assert.equal(await page.locator('.menu-item').count(),8,'filter should show eight burgers');
 await page.locator('button[data-filter="all"]').click();
 assert.equal(await page.locator('.menu-item').count(),26);
 await page.locator('#menuGrid button[data-add="district"]').click();
 assert.equal(await page.locator('#cartCount').textContent(),'1');
 await page.locator('#cartTrigger').click();
 assert.equal(await page.locator('#cartDrawer').getAttribute('aria-hidden'),'false');
 assert.match(await page.locator('#cartTotal').textContent(),/38/);
 await page.locator('#cartItems button[data-qty="1"]').click();
 assert.match(await page.locator('#cartTotal').textContent(),/76/);
 await page.locator('#cartItems button[data-qty="-1"]').click();
 assert.match(await page.locator('#cartTotal').textContent(),/38/);
 await page.locator('#checkout').click();
 assert.equal(await page.locator('#cartCount').textContent(),'0');
 assert.match(await page.locator('#toast').textContent(),/DEMO ORDER CONFIRMED/);
 console.log('PASS demo cart: add, quantities, subtotal, checkout');
 await page.locator('#storyTriggerTwo').click();
 assert.equal(await page.locator('#storyModal').isVisible(),true);
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('#storyModal').isVisible(),false);
 console.log('PASS story modal and Escape');

 // V2: verify each newly approved interaction, not just visual markup.
 assert.equal(await page.locator('.ingredient').count(),10,'ingredient assembly must have 10 real separate layers');
 assert.equal(await page.locator('#assemblyReplay').count(),1,'replay the assembly control');
 const builder=page.locator('#builder');
 assert.equal(await builder.isVisible(),true);
 await page.locator('#builder [data-choice="patty"][data-value="chicken"]').click();
 await page.locator('#builder [data-choice="cheese"][data-value="swiss"]').click();
 await page.locator('#builder [data-extra="double"]').click();
 assert.equal(await page.locator('#buildPrice').textContent(),'AED 46','live price must recalculate after selections');
 assert.equal(await page.locator('#builderBurger').getAttribute('data-patty'),'chicken');
 await page.locator('#addBuild').click();
 assert.equal(await page.locator('#cartCount').textContent(),'1','custom burger must be added');
 await page.locator('#cartTrigger').click();
 assert.match(await page.locator('#cartTotal').textContent(),/46/);
 await page.locator('#cartClose').click();
 console.log('PASS burger ingredients, reassembly control, build your own choices, price and add to bag');
 await page.locator('#menuGrid button[data-add="district"]').click();
 assert.equal(await page.locator('#upgradePopup').isVisible(),true,'upsell should open after burger addition');
 await page.locator('#upgradeYes').click();
 assert.equal(await page.locator('#upgradePopup').isVisible(),false);
 await page.locator('#cartTrigger').click();
 assert.match(await page.locator('#cartTotal').textContent(),/112/,'combo upgrade should add AED 28 to existing build and burger');
 await page.locator('#cartClose').click();
 console.log('PASS add-on combo after burger selection');
 await page.locator('#languageToggle').click();
 assert.equal(await page.locator('html').getAttribute('dir'),'rtl');
 assert.match(await page.locator('#menuGrid .menu-item').first().locator('h3').textContent(),/الديستريكت/);
 assert.match(await page.locator('.hero-title').textContent(),/برجر/);
 await page.locator('#languageToggle').click();
 assert.equal(await page.locator('html').getAttribute('dir'),'ltr');
 assert.match(await page.locator('.hero-title').textContent(),/BURGER/);
 console.log('PASS complete Arabic/English RTL switch and localized menu');
 await page.locator('#soundToggle').click();
 assert.equal(await page.locator('#soundToggle').getAttribute('aria-pressed'),'true');
 await page.locator('#soundToggle').click();
 assert.equal(await page.locator('#soundToggle').getAttribute('aria-pressed'),'false');
 assert.equal(await page.locator('#drops').count(),1);
 assert.equal(await page.locator('#social').count(),1);
 assert.equal(await page.locator('#lastCta').count(),1);
 console.log('PASS opt-in sound toggle, editorial limited drop, social gallery, cinematic CTA');
 await page.screenshot({path:'smash-desktop.png',fullPage:true,timeout:20000});
 const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
 mobile.on('pageerror',e=>errors.push('MOBILE '+e.message));
 await mobile.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle',timeout:35000});
 await mobile.waitForFunction(()=>document.querySelector('#loading')?.classList.contains('done'),undefined,{timeout:7000});
 await mobile.locator('#menuToggle').click();
 assert.equal(await mobile.locator('#mobileMenu').isVisible(),true);
 await mobile.locator('#mobileMenu a[href="#menu"]').click();
 assert.equal(await mobile.locator('#mobileMenu').isVisible(),false);
 await mobile.locator('#menuGrid button[data-add="truffle"]').click();
 assert.equal(await mobile.locator('#cartCount').textContent(),'1');
 await mobile.screenshot({path:'smash-mobile.png',fullPage:false,timeout:20000});
 assert.equal(errors.length,0,errors.join('\n'));
 console.log('PASS mobile navigation, ordering, and no uncaught JavaScript errors');
 await mobile.close();
 await page.close();
}finally{await browser.close();}
